/**
 * 把 LLM/聊天 UI 常见的"美化字符"转回真正能 JSON.parse 的 ASCII。
 *
 * 双弯引号 U+201C / U+201D 智能替换（关键）：
 *   - " 紧跟在 [ { , : / 行首 / 空白 之后 → JSON 字符串边界，转成 "
 *   - " 紧靠在 ] } , : / 行尾 / 空白 之前 → JSON 字符串边界，转成 "
 *   - 其他位置（夹在中文里）→ 内层强调引号，转义成 \" 写进字符串
 *
 *   为什么要这么麻烦：LLM 经常生成
 *     "remediation":"用"几个几"来想"
 *   朴素全替换 → "用"几个几"来想" → 仍然 parse 失败。
 *
 * 其他常见坑：
 *   - U+2018 U+2019 → '       (单弯引号)
 *   - U+2013 U+2014 U+2212 → -  (各种横线被"美化"成 unicode 减号 → 数字字段炸)
 *   - U+00A0 / U+2007 / U+202F → 空格   (各种不间断空格)
 *   - U+200B/C/D / U+FEFF        → 删除 (零宽字符 / BOM)
 *   - ```json ... ``` markdown 围栏
 *
 * 注意：所有特殊字符都用 \uXXXX 写，因为这些字符大多不可见，文本里直接写
 * 容易在编辑器/复制粘贴时被搞丢（曾经吃过亏）。
 */
export function normalizeJsonText(raw: string): string {
  let s = raw.trim();

  // 去掉 ```json ... ``` 围栏
  if (s.startsWith("```")) {
    s = s.replace(/^```(?:json|JSON)?\s*/i, "").replace(/```\s*$/, "");
  }

  s = s
    // 智能替换中文/排印双弯引号
    .replace(/(^|[\s\[\{,:])“/g, '$1"')              // " 在 JSON 边界 → "
    .replace(/”(?=[\s\]\},:]|$)/g, '"')              // " 在 JSON 边界 → "
    .replace(/[“”„‟«»]/g, '\\"') // 内层 → 转义 \"
    // 单弯引号
    .replace(/[‘’‚‛′]/g, "'")
    // 各种横线 → ASCII -
    .replace(/[–—−]/g, "-")
    // 各种不间断空格 → 普通空格
    .replace(/[   ]/g, " ")
    // 零宽字符 / BOM → 删除
    .replace(/[​‌‍﻿]/g, "");

  return s;
}
